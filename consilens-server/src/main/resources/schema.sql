    node_key VARCHAR(128) NOT NULL UNIQUE,
    host VARCHAR(64) NOT NULL,
    port INT NOT NULL,
    machine_code VARCHAR(128),
    status VARCHAR(32) NOT NULL,
    load_average DOUBLE,
    available_memory_mb DOUBLE,
