    redacted_args CLOB,
    args_digest VARCHAR(64),
    idempotency_key VARCHAR(64),
    action_digest VARCHAR(64),
    result_event_seq BIGINT,
    error_code VARCHAR(64),
    retryable BOOLEAN,
    result_summary VARCHAR(1024),
    started_at TIMESTAMP,
    ended_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_cs_ai_tool_call_session_idem ON cs_ai_tool_call (session_id, idempotency_key);

