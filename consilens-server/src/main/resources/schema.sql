    plan_id VARCHAR(64) NOT NULL,
    action_id VARCHAR(64) NOT NULL,
    sequence INT NOT NULL,
    action_type VARCHAR(40) NOT NULL,
    name VARCHAR(160),
    safe_args_json CLOB,
