CREATE TABLE IF NOT EXISTS cs_ai_session (
    id VARCHAR(64) PRIMARY KEY,
    actor_id VARCHAR(128) NOT NULL,
    request_id VARCHAR(64),
    title VARCHAR(128),
    objective VARCHAR(1024),
    status VARCHAR(32) NOT NULL,
    workflow_stage VARCHAR(32) NOT NULL,
    active_run_id VARCHAR(64),
    next_seq BIGINT NOT NULL DEFAULT 0,
    snapshot_seq BIGINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    lease_owner VARCHAR(128),
    lease_expires_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cs_ai_session_actor_updated ON cs_ai_session (actor_id, updated_at);
CREATE INDEX IF NOT EXISTS idx_cs_ai_session_status_lease ON cs_ai_session (status, lease_expires_at);

CREATE TABLE IF NOT EXISTS cs_ai_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL,
    session_id VARCHAR(64) NOT NULL,
    seq BIGINT NOT NULL,
    run_id VARCHAR(64),
    turn_id VARCHAR(64),
    event_type VARCHAR(48) NOT NULL,
    visibility VARCHAR(24) NOT NULL,
    schema_version INT NOT NULL,
    payload CLOB,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_cs_ai_event_session_seq UNIQUE (session_id, seq)
);
CREATE INDEX IF NOT EXISTS idx_cs_ai_event_session_run_seq ON cs_ai_event (session_id, run_id, seq);

CREATE TABLE IF NOT EXISTS cs_ai_run (
    run_id VARCHAR(64) PRIMARY KEY,
    session_id VARCHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    resume_from_run_id VARCHAR(64),
    status VARCHAR(32) NOT NULL,
    lease_owner VARCHAR(128),
    lease_expires_at TIMESTAMP,
    turn_count INT NOT NULL DEFAULT 0,
    tool_call_count INT NOT NULL DEFAULT 0,
    token_count BIGINT NOT NULL DEFAULT 0,
    error_code VARCHAR(64),
    started_at TIMESTAMP,
    ended_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_cs_ai_run_session_request UNIQUE (session_id, request_id)
);

CREATE TABLE IF NOT EXISTS cs_ai_tool_call (
